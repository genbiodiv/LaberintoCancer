export const SCENARIO_LIST: ScenarioDefinition[] = [
  SCENARIOS.A,
  SCENARIOS.B,
  SCENARIOS.C,
  SCENARIOS.D,
];

/**
 * Returns the RoundDefinition for any round from 1 to 10.
 * Rounds beyond the scenario's base sequence cycle adaptively through its late-stage rounds
 * so extended 6–10 round sessions always have full barriers, strategies, and prediction gates.
 */
export function getScenarioRound(scenarioId: ScenarioId, roundNumber: number): RoundDefinition {
  const safeId = scenarioId === 'UNIFIED' ? 'A' : scenarioId;
  const scenario = SCENARIOS[safeId];
  const baseRounds = scenario.rounds;
  const idx = Math.max(0, roundNumber - 1);
  if (idx < baseRounds.length) {
    return baseRounds[idx];
  }
  const adaptivePool = baseRounds.slice(1);
  const template = adaptivePool[(idx - baseRounds.length) % adaptivePool.length] ?? baseRounds[baseRounds.length - 1];
  return {
    ...template,
    roundNumber,
    title: `${template.title} (Fase ${roundNumber})`,
  };
}

